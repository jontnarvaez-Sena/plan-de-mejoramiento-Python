"""
Entrada: nombre, edad, ficha y promedio. Salida: mostrar cada dato con una etiqueta.
"""

nombre = input("Ingrese el nombre completo: ")
edad = int(input("Ingrese la edad: "))
ficha = input("Ingrese el número de ficha: ")
promedio = float(input("Ingrese el promedio académico: "))
print("Nombre:", nombre)
print("Edad:", edad)
print("Ficha:", ficha)
print("Promedio académico:", promedio)
