"""
Entrada: número de participantes y valor de inscripción. Proceso: multiplicar. Salida: recaudo total.
"""

participantes = int(input("Ingrese el número de participantes: "))
inscripcion = float(input("Ingrese el valor de inscripción por persona: "))
recaudo = participantes * inscripcion
print("Recaudo total:", recaudo)

